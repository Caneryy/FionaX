#!/usr/bin/env node
/**
 * Generates the homepage tool list from each `app/tools/<slug>/manifest.ts`.
 *
 * Why this exists
 * ----------------
 * Each tool already owns its own route file (`app/tools/<slug>/page.tsx`), so
 * routing never conflicts between contributors. The one shared file left was
 * `lib/constants.ts`, which every new tool had to edit by hand to appear on
 * the homepage. This script removes that last shared edit: a tool is
 * discovered the moment its directory has a `manifest.ts`, and the generated
 * file is gitignored, so dozens of tool branches can be open at once without
 * ever touching the same line of `lib/constants.ts`.
 *
 * Run on predev, prebuild, pretest and postinstall. `npm run tools:registry`
 * runs it directly.
 */

import { readdir, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const toolsDir = path.join(root, "app", "tools");
const outputPath = path.join(root, "lib", "tools.generated.ts");

const BANNER = `// AUTO-GENERATED by scripts/generate-tools.mjs — do not edit, do not commit.
// Run \`npm run tools:registry\` to refresh.
`;

function identifier(slug) {
  return slug.replace(/[^a-zA-Z0-9]+(.)?/g, (_, chr) => (chr ? chr.toUpperCase() : ""));
}

async function discoverSlugs() {
  if (!existsSync(toolsDir)) return [];

  const dirents = await readdir(toolsDir, { withFileTypes: true });
  const slugs = [];

  for (const dirent of dirents) {
    if (!dirent.isDirectory() || dirent.name.startsWith(".") || dirent.name.startsWith("_")) {
      continue;
    }

    const manifestPath = path.join(toolsDir, dirent.name, "manifest.ts");
    const pagePath = path.join(toolsDir, dirent.name, "page.tsx");

    if (!existsSync(manifestPath)) {
      console.warn(`[tools] skipping ${dirent.name}: manifest.ts is missing`);
      continue;
    }
    if (!existsSync(pagePath)) {
      console.warn(`[tools] skipping ${dirent.name}: page.tsx is missing`);
      continue;
    }

    const manifestSource = await readFile(manifestPath, "utf8");
    const declared = manifestSource.match(/slug:\s*"([^"]+)"/)?.[1];
    if (declared && declared !== dirent.name) {
      throw new Error(
        `[tools] app/tools/${dirent.name}/manifest.ts declares slug "${declared}". ` +
          "The slug must match the directory name."
      );
    }

    slugs.push(dirent.name);
  }

  return slugs.sort();
}

function render(slugs) {
  const imports = slugs
    .map((slug) => `import { manifest as ${identifier(slug)} } from "@/app/tools/${slug}/manifest";`)
    .join("\n");

  const entries = slugs.map((slug) => `  ${identifier(slug)}`).join(",\n");

  return `${BANNER}
import type { ToolManifest } from "@/lib/tool-manifest";
${imports}

export type { ToolStatus } from "@/lib/tool-manifest";

export const tools: ToolManifest[] = [
${entries}
];
`;
}

async function main() {
  const slugs = await discoverSlugs();
  await writeFile(outputPath, render(slugs), "utf8");

  console.log(`[tools] ${slugs.length} tool(s) registered`);
  for (const slug of slugs) console.log(`  - ${slug}`);
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
